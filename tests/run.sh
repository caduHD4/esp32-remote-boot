#!/usr/bin/env bash
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
temp=$(mktemp -d); trap 'rm -rf "$temp"' EXIT
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_multi_pc_policy.cpp" -o "$temp/test_multi_pc_policy"
"$temp/test_multi_pc_policy"
g++ -std=c++17 -Wall -Wextra -Werror -I"$root/tests/stubs" "$root/tests/test_config_store.cpp" -o "$temp/test_config_store"
"$temp/test_config_store"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_document_transaction.cpp" -o "$temp/test_document_transaction"
"$temp/test_document_transaction"
g++ -std=c++17 -Wall -Wextra -Werror -fsanitize=address,undefined -fno-omit-frame-pointer "$root/tests/test_core.cpp" -o "$temp/test_core"
"$temp/test_core"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_credential_policy.cpp" -o "$temp/test_credential_policy"
"$temp/test_credential_policy"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_wifi_reconnect.cpp" -o "$temp/test_wifi_reconnect"
"$temp/test_wifi_reconnect"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_discovery_protocol.cpp" -o "$temp/test_discovery_protocol"
"$temp/test_discovery_protocol"
g++ -std=c++17 -Wall -Wextra -Werror -I"$root/tests" "$root/tests/test_discovery_identity.cpp" -lcrypto -o "$temp/test_discovery_identity"
"$temp/test_discovery_identity"
arduinojson=${ARDUINOJSON_INCLUDE:-"$root/.pio/libdeps/esp32c3_4mb/ArduinoJson/src"}
export ARDUINOJSON_INCLUDE="$arduinojson"
if [ ! -f "$arduinojson/ArduinoJson.h" ]; then
  echo "Missing ArduinoJson 7 at $arduinojson; run: pio pkg install -e esp32c3_4mb" >&2
  exit 1
fi
g++ -std=c++17 -Wall -Wextra -Werror -I"$arduinojson" "$root/tests/test_discovery_config.cpp" -o "$temp/test_discovery_config"
"$temp/test_discovery_config"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_boot_dispatch.cpp" -o "$temp/test_boot_dispatch"
"$temp/test_boot_dispatch"
g++ -std=c++17 -Wall -Wextra -Werror -fsanitize=address,undefined "$root/tests/test_power.cpp" -o "$temp/test_power"
"$temp/test_power"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_sinric_policy.cpp" -o "$temp/test_sinric_policy"
"$temp/test_sinric_policy"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_microlink_policy.cpp" -o "$temp/test_microlink_policy"
"$temp/test_microlink_policy"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_microlink_runtime.cpp" -o "$temp/test_microlink_runtime"
"$temp/test_microlink_runtime"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_microlink_io_policy.cpp" -o "$temp/test_microlink_io_policy"
"$temp/test_microlink_io_policy"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_microlink_stream.cpp" -o "$temp/test_microlink_stream"
"$temp/test_microlink_stream"
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_microlink_transport_policy.cpp" -o "$temp/test_microlink_transport_policy"
"$temp/test_microlink_transport_policy"
gcc -std=c11 -Wall -Wextra -Werror -I"$root/components/microlink/src" -c "$root/components/microlink/src/ml_json_scan.c" -o "$temp/ml_json_scan.o"
g++ -std=c++17 -Wall -Wextra -Werror -I"$root/components/microlink/src" "$root/tests/test_microlink_json_scan.cpp" "$temp/ml_json_scan.o" -o "$temp/test_microlink_json_scan"
"$temp/test_microlink_json_scan"
bash "$root/tests/test_shutdown.sh"
bash "$root/tests/test_discovery.sh"
bash "$root/tests/test_efi_helpers.sh"
bash "$root/tests/test_uefi_bootnext.sh"
bash "$root/tests/test_pc_boot.sh"
while IFS= read -r -d '' file; do bash -n "$file"; done < <(find "$root/agent" "$root/installer" "$root/ipxe" "$root/scripts" "$root/tests" -name '*.sh' -print0)
g++ -std=c++17 -Wall -Wextra -Werror "$root/tests/test_http_asset.cpp" -o "$temp/test_http_asset"
"$temp/test_http_asset"
python3 "$root/tests/test_sinric_transport.py"
python3 "$root/tests/test_discovery_profile.py"
python3 "$root/tests/test_ipxe_mdns.py"
python3 "$root/tests/test_ipxe_deadline.py"
python3 "$root/tests/test_ipxe_build.py"
python3 "$root/tests/test_embed_local_wifi.py"
python3 "$root/tests/test_main_loop.py"
python3 "$root/tests/test_discovery_vectors.py"
python3 "$root/tests/test_discovery_preparation_route.py"
python3 "$root/tests/test_discovery_runtime.py"
python3 "$root/tests/test_no_ap_policy.py"
python3 "$root/tests/test_microlink_build_config.py"
python3 "$root/tests/test_partition_layout.py"
python3 "$root/tests/test_microlink_vendor.py"
python3 "$root/tests/test_wireguard_reply_route.py"
python3 "$root/tests/test_wireguard_key_promotion.py"
python3 "$root/tests/test_web_asset.py"
python3 "$root/tests/test_dashboard_ui.py"
node "$root/tests/test_dashboard_validation.js"
node "$root/tests/test_dashboard_model.js"
node "$root/tests/test_dashboard_polling.js"
node "$root/tests/test_microlink_dashboard.js"
python3 "$root/scripts/scan_secrets.py"
